"""Every norm-shaped implementation in src/ and service/, with its call sites.

AN INVENTORY, NOT AN ANALYSIS. No grouping, no verdict, no opinion about which of
these are the same question. The four ruled false positives and the implementations
already unified are included, so the list is complete rather than the residue.

  python3 src/write_norm_inventory.py
"""
import os, re, ast, glob, sys, collections

HERE = os.path.dirname(os.path.abspath(__file__)); BASE = os.path.join(HERE, "..")
DOCS = os.path.expanduser("~/Dropbox/Football Archive/docs")
OUT = os.path.join(DOCS, "norm-implementations.md")

# every function that reduces or compares a value, including the ruled false positives
WANTED = {"norm", "_norm", "normalise", "normalize", "person_name",
          "same_axis", "same_figure", "season_key", "_read_locally_UNUSED"}


def sources():
    return sorted(glob.glob(os.path.join(BASE, "src", "*.py"))) + \
           sorted(glob.glob(os.path.join(BASE, "service", "*.py")))


def main():
    defs = []
    for f in sources():
        try:
            src = open(f).read(); tree = ast.parse(src)
        except Exception:
            continue
        lines = src.split("\n")
        for n in ast.walk(tree):
            if isinstance(n, ast.FunctionDef) and n.name in WANTED:
                defs.append({"file": os.path.relpath(f, BASE), "name": n.name,
                             "line": n.lineno,
                             "body": "\n".join(lines[n.lineno - 1:n.end_lineno])})
    # call sites: every line in the corpus that calls one of these by name
    calls = collections.defaultdict(list)
    for f in sources():
        rel = os.path.relpath(f, BASE)
        try:
            lines = open(f).read().split("\n")
        except Exception:
            continue
        for i, l in enumerate(lines, 1):
            for nm in sorted(WANTED):
                if re.search(r"(?<![\w.])" + re.escape(nm) + r"\s*\(", l) and \
                        not re.match(r"\s*def\s+" + re.escape(nm), l):
                    calls[nm].append((rel, i, l.strip()))

    o = ["# Every `norm`-shaped implementation", "",
         "*Generated by `src/write_norm_inventory.py`. An inventory, not an analysis:",
         "no grouping, no verdict, no opinion about which of these answer the same",
         "question. The ruled false positives and the already-unified implementations",
         "are included so the list is complete rather than the residue.*", "",
         f"**{len(defs)} definitions across {len({d['file'] for d in defs})} files.**", "",
         "---", ""]
    for d in sorted(defs, key=lambda x: (x["file"], x["line"])):
        o.append(f"## `{d['name']}` — `{d['file']}` line {d['line']}")
        o.append("")
        o.append("```python")
        o.append(d["body"])
        o.append("```")
        o.append("")
        cs = [c for c in calls.get(d["name"], []) if c[0] == d["file"]]
        if cs:
            o.append("**Call sites in this file — what is being compared:**")
            o.append("")
            o.append("| line | the call, verbatim |")
            o.append("|---:|---|")
            for rel, i, l in cs:
                o.append(f"| {i} | `{l.replace('|', chr(92) + '|')[:150]}` |")
        else:
            o.append("**No call site in this file.**")
        o.append("")
        o.append("---")
        o.append("")
    # calls to person_name from elsewhere -- the one that is imported
    o.append("## Call sites of `readings.person_name` from other files")
    o.append("")
    o.append("| file | line | the call, verbatim |")
    o.append("|---|---:|---|")
    for rel, i, l in calls.get("person_name", []):
        if rel != "src/readings.py":
            o.append(f"| `{rel}` | {i} | `{l.replace('|', chr(92) + '|')[:120]}` |")
    o.append("")
    os.makedirs(DOCS, exist_ok=True)
    open(OUT, "w").write("\n".join(o) + "\n")
    print(f"{len(defs)} definitions written to {OUT}")
    by = collections.Counter(d["name"] for d in defs)
    for k, v in by.most_common():
        print(f"   {k:22s} {v}")


if __name__ == "__main__":
    main()
