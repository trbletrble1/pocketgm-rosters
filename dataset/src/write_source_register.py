"""Regenerate `what-we-have-and-have-not-read.md` from the disk and the stores.

Written as a script because the register goes stale the moment anyone ingests
anything, and a document maintained by hand goes stale silently. Same shape as
write_hunting_docs.py: read the measurements, write the page, never edit the page.

  python3 src/write_source_register.py
"""
import os, sys, json, glob, sqlite3, collections

HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
BASE = os.path.join(HERE, "..")
sys.path.insert(0, os.path.join(BASE, "service"))
import paths
import gate_source_coverage as GSC
DOCS = os.path.expanduser("~/Dropbox/Football Archive/docs")
SOURCES = os.path.expanduser("~/Documents/pgm3-sources")
OUT = os.path.join(DOCS, "what-we-have-and-have-not-read.md")


def measure():
    conn = sqlite3.connect(paths.READ_MODEL)
    m = {}
    m["files_on_disk"] = sum(len(f) for _, _, f in os.walk(SOURCES))
    m["bytes"] = sum(os.path.getsize(os.path.join(r, f))
                     for r, _, fs in os.walk(SOURCES) for f in fs
                     if os.path.exists(os.path.join(r, f)))
    _, cov = GSC.run(quiet=True)
    m["coverage"] = cov
    # the corpus frame, and how much of it a claim ever cited
    fr = json.load(open(os.path.join(BASE, "build-reports", "corpus-census-frame.json")))
    cited = set()
    for (sr,) in conn.execute("select distinct source_record from claim where source_record is not null"):
        if "#" in sr: cited.add(os.path.basename(sr.split("#", 1)[1].split("@")[0]).strip())
    tot, hit = collections.Counter(), collections.Counter()
    classed = 0
    for r in fr["rows"]:
        st = r["stratum"]; tot[st] += 1
        if r.get("class") is not None: classed += 1
        b = os.path.basename(r.get("path") or "")
        if b in cited or b.rsplit(".", 1)[0] in cited: hit[st] += 1
    m["frame"] = {"total": sum(tot.values()), "classed": classed,
                  "by_stratum": [(s, tot[s], hit.get(s, 0)) for s, _ in tot.most_common()]}
    # leads are READ and parked -- a different register
    leads = collections.Counter()
    for f in glob.glob(os.path.join(BASE, "build", "*.json")):
        try: d = json.load(open(f))
        except Exception: continue
        if isinstance(d, dict) and isinstance(d.get("leads"), list) and d["leads"]:
            leads[os.path.basename(f)[:-5]] = len(d["leads"])
    m["leads"] = leads
    # wikipedia, the flagship of part two
    m["wikipedia"] = [(r[0], r[1]) for r in conn.execute(
        "select predicate,count(*) from claim where store='wikipedia' group by predicate order by 2 desc")]
    return m


def main():
    m = measure()
    cov = m["coverage"]
    w = []; a = w.append
    a("# What we have, and what we have not read\n")
    a(f"*Regenerated by `src/write_source_register.py` from the disk and the stores — "
      f"**not** the declarations. A declaration describes what was taken, which is exactly "
      f"the blind spot.*\n")
    a(f"**{m['files_on_disk']:,} files on disk under `~/Documents/pgm3-sources/` "
      f"({m['bytes']/1e9:.1f} GB).**\n")
    a("**The pattern this exists to fix.** *\"Wikipedia is ingested\"* reads as finished. "
      "It was read for **people**, not for drafts, and nobody wrote that down — so 255 of "
      "the 391 picks in the 1950 draft are missing from a source the archive already "
      "holds and already allows.\n")
    a("---\n")
    a("## Part one — acquired, and not read\n")
    a("### What the gate checks, and what it finds\n")
    a("`src/gate_source_coverage.py` enumerates each file-shaped source, collects the "
      "locators the claims cite, and requires every unread file to be declared with a "
      "reason. **It rests on the claims' own `source_record` locators, not on the "
      "`source_record` tables** — RS-G3 is red, 27 of 481 stores declare one, and the "
      "739,486-claim store declares none.\n")
    a("| source | acquired | cited | unread | **undeclared** |\n|---|---|---|---|---|")
    for r in cov["file_shaped"]:
        a(f"| `{r['source']}` | {r['acquired']:,} | {r['cited']:,} | {r['unread']:,} | "
          f"**{r['undeclared']:,}** |")
    und = sum(r["undeclared"] for r in cov["file_shaped"])
    a(f"\n**{und:,} acquired files produce no claim and are explained by no ruling.** "
      "That is the backlog, and the gate is red until each is either read or declared.\n")
    a("**The reference books are the shape a declared unread looks like**: three files, "
      "three unread, **zero undeclared** — held and consultable under the standing ruling "
      "that reference works are consulted and cited, never parsed wholesale. *Unread is "
      "their correct permanent state, not a backlog.* Willis's *Old Leather* covers Ohio "
      "professional football 1920–1935, which is exactly where the archive's empty "
      "club-seasons are.\n")
    a("### The catalogued corpus\n")
    f = m["frame"]
    a(f"`corpus-census-frame.json` catalogued **{f['total']:,} documents** in September, "
      f"and its own `class` field — the one its header says is *\"filled by reading\"* — "
      f"is filled on **{f['classed']}** of them. That job was never done and nothing "
      f"recorded that it wasn't.\n")
    a("| stratum | catalogued | cited by ≥1 claim | never cited |\n|---|---|---|---|")
    for s, t, h in f["by_stratum"]:
        a(f"| {s} | {t:,} | {h:,} | **{t-h:,}** |")
    a("")
    a("*The small legal and hearing strata cite claims under their own source ids rather "
      "than by filename, so their `never cited` above is a matching limit, not a fact.*\n")
    a("### Leads are read, not unread\n")
    a(f"**{sum(m['leads'].values()):,} leads across {len(m['leads'])} stores.** Every one "
      "was extracted, evaluated against the archive and parked by a standing ruling. They "
      "belong in a different register — *decided and waiting* — and listing them as "
      "unread would misrepresent both.\n")
    a("---\n")
    a("## Part two — inside a source the archive calls ingested\n")
    a("**The gate cannot see this half, and says so rather than passing over it.** Each "
      "source below is declared not-file-shaped, with the reason it has no denominator, "
      "and is reported as NOT COVERED.\n")
    d = json.load(open(GSC.DECL))
    for sid in sorted(k for k in d["not_file_shaped"] if not k.startswith("_")):
        spec = d["not_file_shaped"][sid]
        if sid in ("wikipedia-en", "statscrew", "pro-football-archives", "psf-photos"):
            a(f"**`{sid}`** — *{spec['unit']}*. {spec['why_no_denominator']}\n")
    n = len([k for k in d["not_file_shaped"] if not k.startswith("_")])
    a(f"A further {n-4} single documents and fetched feeds are declared the same way: a "
      "source that IS one document, or a remote dataset, has no local directory to "
      "enumerate.\n")
    a("### Wikipedia, predicate by predicate\n")
    a("Every one is person-scoped. There is no club, season, draft or standings article "
      "in the store at all — the draft fields come from *player* infoboxes, one man at a "
      "time.\n")
    a("```")
    for p, n_ in m["wikipedia"][:8]: a(f"{p:30s} {n_:>7,}")
    a("```\n")
    a("---\n")
    a("## The limit, stated rather than hidden\n")
    a("The gate holds the file-shaped half. **It cannot hold the other half, and no gate "
      "can.** The unit is not a file: Wikipedia's failure is an article read for one kind "
      "of fact and not another, and nothing on disk records that a page had a draft table "
      "nobody looked at. To check it, a gate would have to know what a source *could* "
      "have yielded — and that knowledge only exists after somebody reads it.\n")
    a("So the other half needs a sentence the ingest author writes: **what I read this "
      "source for, and what I left.** No gate can check that sentence is *true* — only "
      "that it exists.\n")
    open(OUT, "w").write("\n".join(w))
    print(f"  {os.path.basename(OUT)}  {len('\n'.join(w)):,} bytes")
    print(f"  undeclared backlog: {und:,} files")


if __name__ == "__main__":
    main()
